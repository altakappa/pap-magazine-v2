-- 121 — 상한에 걸렸을 뿐인 '실패' 기록을 지워 재시도시킨다 (2026-08-11)
--
-- ⚠️ 실행 순서 — 반드시 배포 뒤에 돌려라
--   1) MAX_BYTES 30MB 커밋을 푸시 → Vercel 배포 READY 확인
--   2) 그 다음에 이 SQL 실행
--   순서를 바꾸면 15MB 상한이 아직 살아 있는 채로 재시도가 돌아,
--   같은 사진들이 곧바로 다시 '실패'로 등재된다(그리고 영구 제외로 굳는다).
--
-- ■ 왜
-- wix 우선 이관 첫 회차(2026-08-11 00:10 UTC)에서 13장이 'too large' 로 기록됐다.
-- 실측 크기 15.9 ~ 24.7MB — 죽은 링크가 아니라 **멀쩡한 원본**이 상한에 걸린 것이다.
-- image_migration_failures 에 오른 URL 은 external_image_editorials 가 영구히
-- 건너뛴다. 즉 이대로 두면 **가장 위험한 wix 사진 13장이 영영 남의 서버에 남는다.**
--
-- 118 에서 똑같은 구조의 사고를 한 번 치웠다(주간 점검이 만든 헛 timeout 24건).
-- 그때 배운 것: **실패 표는 '다시는 시도 안 함' 이라는 뜻이므로, 우리 쪽 설정
-- 때문에 실패한 것은 절대 여기 남겨두면 안 된다.**
--
-- ■ 지우는 범위 — 새 상한(30MB) 안에 들어오는 것만
-- 고정 목록이 아니라 규칙으로 지운다. 배포 전까지 회차가 더 돌아 같은 사유가
-- 더 쌓여도 이 SQL 한 번이면 전부 걷힌다.
-- 구 S3 의 58~98MB 14장은 30MB 로도 못 넘으므로 **일부러 남긴다** —
-- 지워봐야 재시도해서 또 실패하고, 그 사이 시간 예산만 먹는다. (리사이즈 별건)
--
-- ■ 되돌리기
--   되돌릴 것이 없다. 지워진 행은 다음 크론이 재시도해서, 성공하면 이관되고
--   실패하면 같은 사유로 다시 기록된다.

delete from public.image_migration_failures
where reason like 'too large:%'
  and (split_part(reason, ': ', 2))::bigint <= 30 * 1024 * 1024;

-- ② 'storage: ...' 도 함께 지운다 — 우리 쪽(업로드) 실패이지 원본 문제가 아니다.
--
-- 3주간 딱 4건이다(업로드 수천 건 중). 원본이 사라진 게 아니라 스토리지 API 가
-- 그 순간 거절한 것이고, 재시도하면 대개 통과한다. 그런데 지금 구조에서는
-- **한 번 거절당하면 영구 제외**다. 4건 재시도 비용은 사실상 0이다.
--
-- ■ 이게 이 표의 구조적 문제다 (다음 사람이 볼 것)
-- image_migration_failures 는 '다시는 시도 안 함' 이라는 뜻인데,
-- 지금은 성격이 전혀 다른 셋을 한 칸에 넣고 있다:
--     (a) 진짜 영구   — HTTP 404 · 410 · not an image (원본이 없다)
--     (b) 우리 설정   — too large (상한을 올리면 된다)
--     (c) 일시적      — storage 에러 · 네트워크 (다시 하면 된다)
-- (b)(c) 를 영구로 굳히는 바람에 118 · 121 두 번 손으로 치웠다.
-- 근본 해법은 사유별 재시도 정책(예: 시도 횟수 컬럼)인데, 이관이 끝난 뒤에 한다.
-- 지금 그걸 건드리면 진행 중인 wix 구제가 늦어진다.
delete from public.image_migration_failures
where reason like 'storage:%';
