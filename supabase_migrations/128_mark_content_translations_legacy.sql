--   · 영어      → articles.title_en / articles.content_en (기사 생성 시 함께 만듦)
--                  SSR /en/ 이 읽는 곳도 여기다 (seoRenderer 의 _enBody)
--   · 그 외 언어 → seo_translations (kind, content_id, lang, title, description, body)
