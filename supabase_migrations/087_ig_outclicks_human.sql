-- 087 — 사람 아웃클릭만 보는 뷰 (2026-07-21)
--
-- 배경: ig_outclicks 의 과거 데이터는 크롤러로 오염돼 있다. 7/16 시드 기사
-- 대량 발행 → 사이트맵 갱신 → 크롤러가 SSR 페이지의 /api/ig-out 링크를 일제히
-- 따라가며 'ssr' 소스가 하루 1,000~2,900회로 튀었다.
--
-- 봇 필터 자체는 2026-07-20 11:11 (커밋 fbd2c87) 에 이미 배포됐다.
-- 그 시각 이후 기록은 사람만 남는다. 문제는 **그 이전 과거 데이터**로,
-- 지표를 볼 때마다 허수가 섞여 "웹→IG 유입이 급감했다"처럼 잘못 읽힌다.
-- (실제로 2026-07-21 분석에서 그렇게 오독할 뻔했다 — 감소가 아니라 필터 적용이었다.)
--
-- 정책: 과거 행을 지우지 않는다(원본 보존). 대신 이 뷰로만 지표를 읽는다.
-- 삭제는 사람이 판단한다 (CLAUDE.md).

CREATE OR REPLACE VIEW public.ig_outclicks_human AS
SELECT *
FROM public.ig_outclicks
WHERE clicked_at >= TIMESTAMPTZ '2026-07-20 11:11:00+09'  -- 봇 필터 배포 시각
   OR src <> 'ssr';                                        -- 그 이전은 ssr 만 오염

COMMENT ON VIEW public.ig_outclicks_human IS
  '크롤러 오염을 제거한 웹→IG 아웃클릭. 지표·리포트는 이 뷰를 쓴다 (087, 2026-07-21).';
